import type { LectureNotes } from '@/types';

/**
 * Generates an ASCII mind-map and concept tree from lecture notes,
 * inspired by ascii-magic and obsidian terminal workflows.
 */
export function generateAsciiMindMap(notes: LectureNotes): string {
  const line = '═'.repeat(68);
  const thinLine = '─'.repeat(68);
  const title = notes.title.slice(0, 60);
  const words = notes.metadata?.wordCount ? `${notes.metadata.wordCount} words` : '';
  const date = notes.metadata?.generatedAt
    ? new Date(notes.metadata.generatedAt).toLocaleDateString()
    : '';

  let out = '';
  out += `╔${line}╗\n`;
  out += `║  📚 LECTURE AI ARCHIVE: ${title.padEnd(59)}║\n`;
  if (words || date) {
    const meta = `Source: ${notes.metadata?.originalFilename?.slice(0, 30) || 'Lecture'} | ${words} | ${date}`;
    out += `║  ${meta.padEnd(66)}║\n`;
  }
  out += `╚${line}╝\n\n`;

  // Executive Summary
  if (notes.summary) {
    out += `┌─ 📋 EXECUTIVE SUMMARY\n`;
    const cleanSummary = notes.summary.replace(/\n+/g, ' ').slice(0, 240);
    out += `│  ${cleanSummary}...\n`;
    out += `└${thinLine}\n\n`;
  }

  // Key Concepts Tree
  out += `┌─ 🧠 CORE CONCEPT MAP\n`;
  if (notes.keyConcepts && notes.keyConcepts.length > 0) {
    notes.keyConcepts.forEach((concept, idx) => {
      const isLast = idx === notes.keyConcepts.length - 1;
      const branch = isLast ? '└──' : '├──';
      const pipe = isLast ? '   ' : '│  ';
      out += `│  ${branch} [${concept.importance ? concept.importance.toUpperCase() : 'CORE'}] ${concept.concept}\n`;
      out += `│  ${pipe}   ${concept.explanation.slice(0, 80)}...\n`;
    });
  } else {
    out += `│  └── (No distinct concepts extracted)\n`;
  }
  out += `└${thinLine}\n\n`;

  // Definitions
  if (notes.definitions && notes.definitions.length > 0) {
    out += `┌─ 📖 DEFINITIONS & GLOSSARY\n`;
    notes.definitions.slice(0, 8).forEach((def, idx) => {
      const isLast = idx === Math.min(notes.definitions.length, 8) - 1;
      const branch = isLast ? '└──' : '├──';
      out += `│  ${branch} ${def.term}: ${def.definition.slice(0, 75)}...\n`;
    });
    out += `└${thinLine}\n\n`;
  }

  // Action Items / Review
  if (notes.actionItems && notes.actionItems.length > 0) {
    out += `┌─ 🎯 ACTION & REVISION CHECKLIST\n`;
    notes.actionItems.forEach((action, idx) => {
      const isLast = idx === notes.actionItems.length - 1;
      const branch = isLast ? '└──' : '├──';
      out += `│  ${branch} [ ] ${action.slice(0, 80)}\n`;
    });
    out += `└${thinLine}\n\n`;
  }

  out += `[ Generated by Lecture-AI (talk2notes) • Ready for Obsidian, Notion & Terminal ]\n`;
  return out;
}
